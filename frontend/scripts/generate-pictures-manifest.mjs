// Regenerates the Transcendence showcase's picture list from whatever is on disk in
// public/pictures/. Runs automatically before `npm start` / `npm run build` (see package.json
// "prestart"/"prebuild") so dropping a new image in that folder and re-running either command
// is all that's needed - no component/code changes required.
import { readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const picturesDir = join(__dirname, '..', 'public', 'pictures');
const outFile = join(__dirname, '..', 'src', 'app', 'features', 'dashboard', 'transcendence-pictures.manifest.ts');

const IMAGE_EXTENSIONS = new Set(['.png', '.jpg', '.jpeg', '.webp', '.gif', '.svg', '.avif']);

mkdirSync(picturesDir, { recursive: true });

const files = readdirSync(picturesDir)
  .filter((name) => IMAGE_EXTENSIONS.has(name.slice(name.lastIndexOf('.')).toLowerCase()))
  .sort((a, b) => a.localeCompare(b));

const banner = `// AUTO-GENERATED by scripts/generate-pictures-manifest.mjs - do not edit by hand.
// Regenerated automatically on \`npm start\` / \`npm run build\` (see package.json). To pick up
// new images immediately without a full start/build, run \`npm run generate:pictures\`.`;

const body = `${banner}

/** Public URLs (served from public/pictures/) of every image currently in that folder. */
export const TRANSCENDENCE_PICTURES: readonly string[] = [
${files.map((name) => `  '/pictures/${name}',`).join('\n')}
];
`;

writeFileSync(outFile, body);
console.log(`generate-pictures-manifest: wrote ${files.length} picture(s) to ${outFile}`);
